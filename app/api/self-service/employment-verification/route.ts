import {NextResponse} from 'next/server';
import {PDFDocument,StandardFonts,rgb} from 'pdf-lib';
import {randomUUID} from 'crypto';
import {access} from '@/lib/auth';
import {db} from '@/lib/db';
export const runtime='nodejs';
export const dynamic='force-dynamic';
export async function POST(){
 try{
  const a=await access();
  if(!a.user)return NextResponse.json({error:'Unauthenticated'},{status:401});
  if(!a.can('selfservice.view'))return NextResponse.json({error:'Forbidden'},{status:403});
  if(!a.user.employeeId)return NextResponse.json({error:'Account not linked to an employee'},{status:403});
  const e=await db.employee.findUnique({where:{id:a.user.employeeId},select:{id:true,employeeNo:true,firstName:true,lastName:true,hireDate:true,status:true}});
  if(!e||e.status!=='ACTIVE')return NextResponse.json({error:'Only active employees may generate a letter'},{status:403});
  const c=await db.employeeCompensation.findFirst({where:{employeeId:e.id,status:'APPROVED',effectiveDate:{lte:new Date()}},orderBy:[{effectiveDate:'desc'},{createdAt:'desc'}],select:{basicSalary:true,currency:true}});
  if(!c)return NextResponse.json({error:'No effective approved basic salary found. Contact HR.'},{status:409});
  const ref='EVL-'+new Date().toISOString().slice(0,10).replace(/-/g,'')+'-'+randomUUID().slice(0,8).toUpperCase();
  const date=(d:Date)=>d.toLocaleDateString('en-GB',{timeZone:'UTC',day:'numeric',month:'long',year:'numeric'});
  const name=e.firstName+' '+e.lastName;
  const salary=new Intl.NumberFormat('en-GH',{minimumFractionDigits:2,maximumFractionDigits:2}).format(Number(c.basicSalary));
  const doc=await PDFDocument.create();const p=doc.addPage([595,842]);const regular=await doc.embedFont(StandardFonts.Helvetica);const bold=await doc.embedFont(StandardFonts.HelveticaBold);
  const write=(s:string,y:number,size=11,isBold=false)=>p.drawText(s.replace(/[^\x20-\x7E]/g,'-'),{x:52,y,size,font:isBold?bold:regular,color:rgb(.12,.12,.12)});
  write('FLICKS N LICKS',774,20,true);p.drawLine({start:{x:52,y:759},end:{x:543,y:759},thickness:2,color:rgb(.7,.1,.14)});
  write('EMPLOYMENT VERIFICATION LETTER',724,15,true);write('Date: '+date(new Date()),692);write('Reference: '+ref,670,10);
  write('TO WHOM IT MAY CONCERN',627,12,true);write('RE: EMPLOYMENT VERIFICATION',592,12,true);
  const lines=[
   'This letter confirms that '+name+' is currently employed by Flicks n Licks.',
   'Employee name: '+name,
   'Employee ID: '+e.employeeNo,
   'Date of joining: '+date(e.hireDate),
   'Current monthly basic salary: '+c.currency+' '+salary,
   '',
   'This letter is issued at the request of the employee for official verification',
   'purposes. For further information, please contact the Human Resources',
   'Department through the company official communication channels.'
  ];let y=551;for(const line of lines){write(line,y);y-=26;}
  write('Yours faithfully,',260);write('Human Resources Department',231,11,true);write('Flicks n Licks',211);
  p.drawLine({start:{x:52,y:105},end:{x:543,y:105},thickness:1,color:rgb(.75,.75,.75)});
  write('Electronically generated by Nexora HRMS | '+ref,86,9);write('Authenticity may be verified with the Human Resources Department.',68,9);
  const bytes=await doc.save();
  await db.employeeHRRequest.create({data:{employeeId:e.id,category:'EMPLOYMENT_VERIFICATION_LETTER',subject:'Employment verification letter - '+ref,details:'Self-service letter generated on '+new Date().toISOString(),status:'COMPLETED',response:'Document reference: '+ref}});
  return new NextResponse(Buffer.from(bytes),{headers:{'Content-Type':'application/pdf','Content-Disposition':'attachment; filename="Employment-Verification-'+ref+'.pdf"','Cache-Control':'private, no-store','X-Content-Type-Options':'nosniff'}});
 }catch(error){console.error('ESS letter generation',error);return NextResponse.json({error:'Unable to generate verification letter. Contact HR.'},{status:500});}
}
